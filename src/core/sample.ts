export const SAMPLE_CONTENT = `Reading slowly is a habit that few people cultivate.

We are trained to skim, to scan for the gist, to finish the page and move on. Speed feels like progress. But a book that is finished in a hurry leaves almost nothing behind.

The readers who remember what they read are not the fastest ones. They pause. They copy a sentence into a notebook. They look up a word and write down the sentence it appeared in, because a word without its context is a word they will forget.

This is the whole idea behind this little tool. While you read, mark what strikes you. Keep the word, keep the sentence around it, keep the page you were on. When you come back, everything is still where you left it.

Annotating is not a chore you do for the text. It is how the text becomes yours.`
